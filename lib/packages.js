export function getCategoryBySlug(slug) {
  return categories.find(c => c.slug === slug)
}

export function getAllPackagesForCategory(slug) {
  const cat = getCategoryBySlug(slug)
  if (!cat) return []
  const packages = [...cat.packages]
  if (slug === 'birthday-balloon-sets') packages.push(...girlsPackages)
  if (slug === 'celebration-balloon-sets') packages.push(...forHimPackages)
  return packages
}
